import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const [inventory] = process.argv.slice(2);
if (!inventory || process.argv.length !== 3) {
  console.error(
    "Usage: node helpers/model-runtime/register-alignment.mjs <verified-assembly-manifest.json>",
  );
  process.exit(2);
}
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const inputs = JSON.parse(
  await readFile(new URL("alignment-inputs.json", import.meta.url), "utf8"),
);
const entries = JSON.parse(await readFile(inventory, "utf8"));
const resources = await Promise.all(
  [
    ["prepare.py", "prepare.py"],
    ["assemble.py", "assemble.py"],
    ["native.py", "native.py"],
    ["launch.py", "launch.py"],
    ["worker.py", "../alignment/worker.py"],
  ].map(async ([path, source]) => {
    const content = await readFile(new URL(source, import.meta.url), "utf8");
    return { path, content, sha256: hash(content) };
  }),
);
for (const path of ["execution/worker.py", "execution/launch.py"]) {
  const entry = entries.find((entry) => entry.path === path);
  const source = resources.find((resource) => resource.path === path.split("/")[1]);
  if (entry?.sha256 !== source?.sha256)
    throw new Error("Measured execution entry differs from current source: " + path);
}
const digest = hash(JSON.stringify(entries));
const manifest = {
  name: "nemo-ctc110",
  purpose: "alignment",
  platform: { system: "darwin", architecture: "arm64" },
  repo: "nvidia/parakeet-tdt_ctc-110m",
  revision: "431a349f3051ab85c22b9b7a2741b5fe77065665",
  folderName: "checkpoint",
  engine: {
    runtime: "NeMo",
    runtimeVersion: "2.7.3",
    runtimeRevision: digest,
    decoder: "nemo-auxiliary-ctc110-v1",
  },
  files: [
    {
      path: "parakeet-tdt_ctc-110m.nemo",
      bytes: 459243520,
      sha256: "1e6b5c3bcaa390b479bd8112512ede515d2ef5b61495568f2c266d6d5e680c3a",
    },
  ],
  runtimeArtifact: {
    digest,
    python: "python/bin/python3.12",
    entry: "execution/launch.py",
    acquisition: { ...inputs, resources },
  },
};
const destination = new URL("../../packages/core/src/model-data/", import.meta.url);
const { runtimeArtifact, ...descriptor } = manifest;
await writeFile(
  new URL("alignment-runtime.generated.json", destination),
  JSON.stringify(entries) + "\n",
);
await writeFile(
  new URL("alignment-manifest.generated.ts", destination),
  "// Generated by helpers/model-runtime/register-alignment.mjs from a measured execution inventory.\n" +
    'import type { ModelManifest, RuntimeEntry } from "../model-types.js";\n' +
    'import entries from "./alignment-runtime.generated.json" with { type: "json" };\n' +
    "export const alignmentManifest: ModelManifest = {" +
    "..." +
    JSON.stringify(descriptor) +
    ",runtimeArtifact:{..." +
    JSON.stringify(runtimeArtifact) +
    ",entries:entries as RuntimeEntry[]}};\n",
);
console.log(
  JSON.stringify({ destination: fileURLToPath(destination), digest, entries: entries.length }),
);
